    /**
     * Hook for manipulate query of datatable result
     * @param {current mongo query} query
     * @param {adonis request object} request
     */
    protected static async datatable_query_hook(query:any,request:any)
    {
        let urlParams = new URLSearchParams(request.input('keyword'));
        if( !_.isEmpty(urlParams.get('keyword')) ){
            let keyword = urlParams.get('keyword');
            query.where( function(query){
              query.where('name','like',`${keyword}%`)
                    .orWhere('email','like',`${keyword}%`)
                    .orWhere('mobile_no','like',`${keyword}%`)
            })
        }
        query.where('users.user_group_id',3);
    }
